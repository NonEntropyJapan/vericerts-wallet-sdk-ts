/**
 * KDF を通るテストの共有タイムアウト。規則の実体を 1 箇所に置く。
 *
 * KDF は意図的に計算コストが高い。テストの「準備」で実 KDF を通す箇所と、「鍵導出前に弾かれる」
 * ことを主張する箇所とでは必要な猶予が 2 桁以上違うため、両者を別の定数として明示的に分ける。
 *
 * 実測（本ファイル追加時、10 コア機。`bun test` フルスイート 449 ファイル並列実行の文脈）:
 * - 実 argon2id 1 回（m=9216 KiB / t=4 / p=1）の encrypt: 静穏時 368〜819 ms、飽和負荷下 355〜680 ms
 * - kdfJson 差し替え + 鍵導出前 reject: 0.1〜1.9 ms
 *
 * KDF を通る側は静穏時の実測ですら 819 ms に達し、pre-push（lefthook `parallel: true` で
 * sdk と extension のテストが同時実行される）や CI の低コア環境ではさらに大きく振れる。
 * argon2id はメモリハードなので、CPU だけでなくメモリ帯域の競合でも劣化する。
 */

/**
 * 実 KDF 導出を通るステップ用の猶予。負荷依存で大きく振れるため広く取る。
 * ハング検知は保ちつつ、CPU/メモリ帯域の競合では落ちない水準。
 * extension 側の `ARGON2_TIMEOUT_MS`と同じ思想・同じ値に揃えている。
 *
 * `bun:test` は `beforeAll`/`beforeEach` の第 2 引数のタイムアウトを尊重する（検証済み）。
 * KDF を通る準備は `describe` 側ではなくフック自身に本定数を渡すこと。
 */
export const KDF_TIMEOUT_MS = 120_000;

/**
 * 「鍵導出より前に弾かれる」ことを主張するアサーション用の短い猶予。
 *
 * 実 KDF の混入に対する第一の防御は閾値ではなく構造である。準備（実 encrypt）は `beforeAll` に
 * 追い出し、ケース本体では導出を通さない。本定数はその構造を補う粗い網に過ぎない。
 *
 * 上の実測のとおり実 argon2id 1 回の encrypt は静穏時 368〜819 ms・飽和負荷下 355〜680 ms と
 * いずれも 1 000 ms 未満なので、ケース本体に実 KDF が 1 回混入しても静穏時は予算内に収まり、
 * 確実には検知できない。捕まえられるのは、負荷が乗って予算を超えた場合と、複数回の導出や
 * 極端に遅い経路といった粗い退行である。
 *
 * 一方、導出前 reject だけのケース本体は実測 0.1〜1.9 ms で本予算に 500 倍以上の余裕があり、
 * この閾値が flaky の原因になることはない。
 *
 * この予算を使うテストは本体で実 KDF を通さないこと（準備は `beforeAll` 等へ追い出し、
 * そちらに `KDF_TIMEOUT_MS` を与える）。
 */
export const PRE_KDF_TIMEOUT_MS = 1_000;
