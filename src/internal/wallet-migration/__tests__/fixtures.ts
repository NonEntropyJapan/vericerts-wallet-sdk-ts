/**
 * W2W モジュールテスト共通フィクスチャ。
 *
 * ES256（P-256）の `BackupSigner` と対応する公開鍵 JWK を、`keymanager/signer.ts` の
 * P-256 プリミティブから決定論的に構築する。テスト専用のため index.ts からは再エクスポートしない。
 */

import { base64urlnopad } from '@scure/base';
import { getP256PublicKey, signP256 } from '../../keymanager/signer.js';
import type { BackupSigner, JWK } from '../types.js';

/** 固定の P-256 秘密鍵（RFC6979 テストベクタと同一値。テスト専用）。 */
const TEST_PRIVATE_KEY = new Uint8Array([
  0xc9, 0xaf, 0xa9, 0xd8, 0x45, 0xba, 0x75, 0x16, 0x6b, 0x5c, 0x21, 0x57, 0x67, 0xb1, 0xd6, 0x93,
  0x4e, 0x50, 0xc3, 0xdb, 0x36, 0xe8, 0x9b, 0x12, 0x7b, 0x8a, 0x62, 0x2b, 0x12, 0x0f, 0x67, 0x21,
]);

/** テスト用 P-256 公開鍵 JWK（`crv: 'P-256'`）を構築する。 */
export function testPublicKeyJwk(privateKey: Uint8Array = TEST_PRIVATE_KEY): JWK {
  const uncompressed = getP256PublicKey(privateKey, false);
  return {
    kty: 'EC',
    crv: 'P-256',
    x: base64urlnopad.encode(uncompressed.subarray(1, 33)),
    y: base64urlnopad.encode(uncompressed.subarray(33, 65)),
  };
}

/** テスト用 ES256 BackupSigner を構築する。 */
export function testSigner(
  keyId = 'did:key:test#0',
  privateKey: Uint8Array = TEST_PRIVATE_KEY,
): BackupSigner {
  return {
    keyId,
    publicKeyJwk: testPublicKeyJwk(privateKey),
    sign: (digest: Uint8Array): Uint8Array => signP256(digest, privateKey),
  };
}

